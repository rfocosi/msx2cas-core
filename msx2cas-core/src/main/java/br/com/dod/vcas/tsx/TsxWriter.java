package br.com.dod.vcas.tsx;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;

import br.com.dod.vcas.tape.TapeBlock;
import br.com.dod.vcas.tape.TapeBlock.ArchiveInfoBlock;
import br.com.dod.vcas.tape.TapeBlock.CustomInfoBlock;
import br.com.dod.vcas.tape.TapeBlock.DirectRecordingBlock;
import br.com.dod.vcas.tape.TapeBlock.GeneralizedDataBlock;
import br.com.dod.vcas.tape.TapeBlock.GeneralizedDataBlock.PilotRle;
import br.com.dod.vcas.tape.TapeBlock.GeneralizedDataBlock.SymbolDef;
import br.com.dod.vcas.tape.TapeBlock.GlueBlock;
import br.com.dod.vcas.tape.TapeBlock.GroupEndBlock;
import br.com.dod.vcas.tape.TapeBlock.GroupStartBlock;
import br.com.dod.vcas.tape.TapeBlock.HardwareTypeBlock;
import br.com.dod.vcas.tape.TapeBlock.HardwareTypeBlock.HardwareEntry;
import br.com.dod.vcas.tape.TapeBlock.KcsBlock;
import br.com.dod.vcas.tape.TapeBlock.LoopEndBlock;
import br.com.dod.vcas.tape.TapeBlock.LoopStartBlock;
import br.com.dod.vcas.tape.TapeBlock.MessageBlock;
import br.com.dod.vcas.tape.TapeBlock.PauseBlock;
import br.com.dod.vcas.tape.TapeBlock.PulseSequenceBlock;
import br.com.dod.vcas.tape.TapeBlock.PureDataBlock;
import br.com.dod.vcas.tape.TapeBlock.PureToneBlock;
import br.com.dod.vcas.tape.TapeBlock.SetSignalLevelBlock;
import br.com.dod.vcas.tape.TapeBlock.StandardSpeedBlock;
import br.com.dod.vcas.tape.TapeBlock.Stop48kBlock;
import br.com.dod.vcas.tape.TapeBlock.TextBlock;
import br.com.dod.vcas.tape.TapeBlock.TurboSpeedBlock;
import br.com.dod.vcas.tape.TapeImage;

/**
 * {@link TsxOutput} serializer that encodes a {@link TapeImage} into TZX 1.21 / TSX container bytes.
 */
public class TsxWriter implements TsxOutput {

    private static final int TZX_MAJOR = 0x01;
    private static final int TZX_MINOR = 0x15; // 1.21
    private static final String GENERATOR_TEXT = "Generated by MSX2Cas 8.0.0";

    private final TapeImage tapeImage;

    /**
     * Create a {@link TsxWriter} wrapping the given {@link TapeImage}.
     *
     * @param tapeImage Tape image to serialize
     */
    public TsxWriter(TapeImage tapeImage) {
        this.tapeImage = tapeImage != null ? tapeImage : new TapeImage("", List.of());
    }

    @Override
    public byte[] toBytes() {
        return toBytes(tapeImage);
    }

    @Override
    public String casName() {
        return tapeImage.casName();
    }

    @Override
    public TapeImage getTapeImage() {
        return tapeImage;
    }

    /**
     * Serialize a {@link TapeImage} into TSX (TZX 1.21) bytes, injecting default {@code #30} / {@code #32}
     * metadata blocks if not already present.
     *
     * @param tapeImage Tape image to serialize
     * @return Complete TSX byte stream
     */
    public static byte[] toBytes(TapeImage tapeImage) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        out.writeBytes(TsxParser.TZX_MAGIC);
        out.write(TZX_MAJOR);
        out.write(TZX_MINOR);

        if (tapeImage == null) {
            return out.toByteArray();
        }

        List<TapeBlock> blocks = tapeImage.getBlocks();
        boolean hasArchiveInfo = false;
        boolean hasTextBlock = false;
        for (TapeBlock block : blocks) {
            if (block instanceof ArchiveInfoBlock) {
                hasArchiveInfo = true;
            } else if (block instanceof TextBlock) {
                hasTextBlock = true;
            }
        }

        if (!hasArchiveInfo && !tapeImage.casName().isEmpty()) {
            writeArchiveInfo(out, new ArchiveInfoBlock(List.of(
                    new ArchiveInfoBlock.Entry(0x00, tapeImage.casName()),
                    new ArchiveInfoBlock.Entry(0xFF, GENERATOR_TEXT))));
        }
        if (!hasTextBlock) {
            writeTextBlock(out, new TextBlock(GENERATOR_TEXT));
        }

        for (TapeBlock block : blocks) {
            writeBlock(out, block);
        }
        return out.toByteArray();
    }

    private static void writeBlock(ByteArrayOutputStream out, TapeBlock block) {
        if (block instanceof StandardSpeedBlock b) {
            byte[] data = b.data();
            out.write(0x10);
            writeU16(out, b.pauseMs());
            writeU16(out, data.length);
            out.writeBytes(data);
        } else if (block instanceof TurboSpeedBlock b) {
            byte[] data = b.data();
            out.write(0x11);
            writeU16(out, b.pilotPulseLen());
            writeU16(out, b.sync1PulseLen());
            writeU16(out, b.sync2PulseLen());
            writeU16(out, b.zeroPulseLen());
            writeU16(out, b.onePulseLen());
            writeU16(out, b.pilotPulses());
            out.write(b.usedBitsInLastByte() & 0xFF);
            writeU16(out, b.pauseMs());
            writeU24(out, data.length);
            out.writeBytes(data);
        } else if (block instanceof PureToneBlock b) {
            out.write(0x12);
            writeU16(out, b.pulseLen());
            writeU16(out, b.pulseCount());
        } else if (block instanceof PulseSequenceBlock b) {
            int[] pulses = b.pulseLengths();
            out.write(0x13);
            out.write(pulses.length & 0xFF);
            for (int pulse : pulses) {
                writeU16(out, pulse);
            }
        } else if (block instanceof PureDataBlock b) {
            byte[] data = b.data();
            out.write(0x14);
            writeU16(out, b.zeroPulseLen());
            writeU16(out, b.onePulseLen());
            out.write(b.usedBitsInLastByte() & 0xFF);
            writeU16(out, b.pauseMs());
            writeU24(out, data.length);
            out.writeBytes(data);
        } else if (block instanceof DirectRecordingBlock b) {
            byte[] samples = b.samples();
            out.write(0x15);
            writeU16(out, b.tStatesPerSample());
            writeU16(out, b.pauseMs());
            out.write(b.usedBitsInLastByte() & 0xFF);
            writeU24(out, samples.length);
            out.writeBytes(samples);
        } else if (block instanceof GeneralizedDataBlock b) {
            writeGeneralizedData(out, b);
        } else if (block instanceof PauseBlock b) {
            out.write(0x20);
            writeU16(out, b.durationMs());
        } else if (block instanceof GroupStartBlock b) {
            byte[] name = toShortLatin1(b.name());
            out.write(0x21);
            out.write(name.length);
            out.writeBytes(name);
        } else if (block instanceof GroupEndBlock) {
            out.write(0x22);
        } else if (block instanceof LoopStartBlock b) {
            out.write(0x24);
            writeU16(out, b.repetitions());
        } else if (block instanceof LoopEndBlock) {
            out.write(0x25);
        } else if (block instanceof Stop48kBlock) {
            out.write(0x2A);
            writeU32(out, 0L);
        } else if (block instanceof SetSignalLevelBlock b) {
            out.write(0x2B);
            writeU32(out, 1L);
            out.write(b.level() != 0 ? 1 : 0);
        } else if (block instanceof TextBlock b) {
            writeTextBlock(out, b);
        } else if (block instanceof MessageBlock b) {
            byte[] text = toShortLatin1(b.text());
            out.write(0x31);
            out.write(b.displaySeconds() & 0xFF);
            out.write(text.length);
            out.writeBytes(text);
        } else if (block instanceof ArchiveInfoBlock b) {
            writeArchiveInfo(out, b);
        } else if (block instanceof HardwareTypeBlock b) {
            List<HardwareEntry> entries = b.entries();
            int count = Math.min(entries.size(), 255);
            out.write(0x33);
            out.write(count);
            for (int i = 0; i < count; i++) {
                HardwareEntry entry = entries.get(i);
                out.write(entry.type() & 0xFF);
                out.write(entry.id() & 0xFF);
                out.write(entry.info() & 0xFF);
            }
        } else if (block instanceof CustomInfoBlock b) {
            byte[] id = b.identification().getBytes(StandardCharsets.ISO_8859_1);
            byte[] data = b.data();
            out.write(0x35);
            for (int i = 0; i < 16; i++) {
                out.write(i < id.length ? (id[i] & 0xFF) : ' ');
            }
            writeU32(out, data.length);
            out.writeBytes(data);
        } else if (block instanceof KcsBlock b) {
            byte[] data = b.data();
            out.write(0x4B);
            writeU32(out, 12L + data.length);
            writeU16(out, b.pauseMs());
            writeU16(out, b.pilotPulseLen());
            writeU16(out, b.pilotPulses());
            writeU16(out, b.zeroPulseLen());
            writeU16(out, b.onePulseLen());
            out.write(b.bitCfg() & 0xFF);
            out.write(b.byteCfg() & 0xFF);
            out.writeBytes(data);
        } else if (block instanceof GlueBlock b) {
            out.write(0x5A);
            out.writeBytes(new byte[] { 'X', 'T', 'a', 'p', 'e', '!', 0x1A });
            out.write(b.majorVersion() & 0xFF);
            out.write(b.minorVersion() & 0xFF);
        }
    }

    private static void writeGeneralizedData(ByteArrayOutputStream out, GeneralizedDataBlock b) {
        ByteArrayOutputStream body = new ByteArrayOutputStream();
        writeU16(body, b.pauseMs());
        writeU32(body, b.totalPilotSymbols());
        body.write(b.maxPulsesPerPilot() & 0xFF);
        int asp = b.pilotSymbols().size();
        body.write(asp == 256 ? 0 : (asp & 0xFF));
        writeU32(body, b.totalDataSymbols());
        body.write(b.maxPulsesPerData() & 0xFF);
        int asd = b.dataSymbols().size();
        body.write(asd == 256 ? 0 : (asd & 0xFF));

        if (b.totalPilotSymbols() > 0) {
            for (SymbolDef def : b.pilotSymbols()) {
                body.write(def.flags() & 0xFF);
                int[] pulses = def.pulseLengths();
                for (int i = 0; i < b.maxPulsesPerPilot(); i++) {
                    writeU16(body, i < pulses.length ? pulses[i] : 0);
                }
            }
            for (PilotRle rle : b.pilotStream()) {
                body.write(rle.symbolIndex() & 0xFF);
                writeU16(body, rle.repetitions());
            }
        }

        if (b.totalDataSymbols() > 0) {
            for (SymbolDef def : b.dataSymbols()) {
                body.write(def.flags() & 0xFF);
                int[] pulses = def.pulseLengths();
                for (int i = 0; i < b.maxPulsesPerData(); i++) {
                    writeU16(body, i < pulses.length ? pulses[i] : 0);
                }
            }
            body.writeBytes(b.dataStream());
        }

        byte[] bodyBytes = body.toByteArray();
        out.write(0x19);
        writeU32(out, bodyBytes.length);
        out.writeBytes(bodyBytes);
    }

    private static void writeTextBlock(ByteArrayOutputStream out, TextBlock block) {
        byte[] text = toShortLatin1(block.text());
        out.write(0x30);
        out.write(text.length);
        out.writeBytes(text);
    }

    private static void writeArchiveInfo(ByteArrayOutputStream out, ArchiveInfoBlock block) {
        ByteArrayOutputStream body = new ByteArrayOutputStream();
        List<ArchiveInfoBlock.Entry> entries = block.entries();
        int count = Math.min(entries.size(), 255);
        body.write(count);
        for (int i = 0; i < count; i++) {
            ArchiveInfoBlock.Entry entry = entries.get(i);
            byte[] text = toShortLatin1(entry.text());
            body.write(entry.id() & 0xFF);
            body.write(text.length);
            body.writeBytes(text);
        }
        byte[] bodyBytes = body.toByteArray();
        out.write(0x32);
        writeU16(out, bodyBytes.length);
        out.writeBytes(bodyBytes);
    }

    private static byte[] toShortLatin1(String s) {
        byte[] raw = (s != null ? s : "").getBytes(StandardCharsets.ISO_8859_1);
        if (raw.length <= 255) {
            return raw;
        }
        byte[] truncated = new byte[255];
        System.arraycopy(raw, 0, truncated, 0, 255);
        return truncated;
    }

    private static void writeU16(ByteArrayOutputStream out, int val) {
        out.write(val & 0xFF);
        out.write((val >>> 8) & 0xFF);
    }

    private static void writeU24(ByteArrayOutputStream out, int val) {
        out.write(val & 0xFF);
        out.write((val >>> 8) & 0xFF);
        out.write((val >>> 16) & 0xFF);
    }

    private static void writeU32(ByteArrayOutputStream out, long val) {
        out.write((int) (val & 0xFFL));
        out.write((int) ((val >>> 8) & 0xFFL));
        out.write((int) ((val >>> 16) & 0xFFL));
        out.write((int) ((val >>> 24) & 0xFFL));
    }
}
